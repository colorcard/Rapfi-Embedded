/**
 * @brief 写单个寄存器。
 * @param reg 寄存器地址。
 * @param data 待写入数据。
 * @return RP_OK 表示成功，其他值表示失败。
 */
static rp_status_t imu660ra_write_register(uint8_t reg, uint8_t data)
{
  return i2c_mem_write(IMU660RA_I2C_BUS, IMU660RA_DEV_ADDR, reg,
                       I2C_MEMADD_SIZE_8BIT, &data, 1U,
                       IMU660RA_I2C_TIMEOUT_MS);
}

/**
 * @brief 读单个寄存器。
 * @param reg 寄存器地址。
 * @param data 读取结果输出。
 * @return RP_OK 表示成功，其他值表示失败。
 */
static rp_status_t imu660ra_read_register(uint8_t reg, uint8_t *data)
{
  if (data == NULL) {
    return RP_INVALID_PARAM;
  }
  return i2c_mem_read(IMU660RA_I2C_BUS, IMU660RA_DEV_ADDR, reg,
                      I2C_MEMADD_SIZE_8BIT, data, 1U,
                      IMU660RA_I2C_TIMEOUT_MS);
}

/**
 * @brief 连续读寄存器（地址自增）。
 * @param reg 起始寄存器地址。
 * @param data 读取结果输出。
 * @param length 字节数。
 * @return RP_OK 表示成功，其他值表示失败。
 */
static rp_status_t imu660ra_read_registers(uint8_t reg, uint8_t *data,
                                           uint16_t length)
{
  if ((data == NULL) || (length == 0U)) {
    return RP_INVALID_PARAM;
  }
  return i2c_mem_read(IMU660RA_I2C_BUS, IMU660RA_DEV_ADDR, reg,
                      I2C_MEMADD_SIZE_8BIT, data, length,
                      IMU660RA_I2C_TIMEOUT_MS);
}

rp_status_t imu660ra_self_check(void)
{
  uint8_t dat = 0U;
  uint16_t timeout_count = 0U;

  do {
    if (timeout_count++ > IMU660RA_TIMEOUT_COUNT) {
      return RP_TIMEOUT;
    }
    if ((imu660ra_read_register(IMU660RA_CHIP_ID, &dat) == RP_OK)
        && (dat == IMU660RA_CHIP_ID_VALUE)) {
      return RP_OK;
    }
    system_delay_ms(1U);
  } while (1);
}

rp_status_t imu660ra_init(void)
{
  rp_status_t status;
  uint8_t dat = 0U;

  system_delay_ms(20U); /* 等待模块上电稳定。 */

  status = i2c_init(IMU660RA_I2C_BUS, NULL);
  if (status != RP_OK) {
    return status;
  }

  status = imu660ra_self_check();
  if (status != RP_OK) {
    return status;
  }

  /* 关闭高级省电模式。 */
  status = imu660ra_write_register(IMU660RA_PWR_CONF, 0x00U);
  if (status != RP_OK) {
    return status;
  }
  system_delay_ms(1U);

  /* 开始加载配置流。 */
  status = imu660ra_write_register(IMU660RA_INIT_CTRL, 0x00U);
  if (status != RP_OK) {
    return status;
  }

  /* 输出配置文件，寄存器地址在 INIT_DATA 窗口内自增。 */
  status = i2c_mem_write(IMU660RA_I2C_BUS, IMU660RA_DEV_ADDR,
                         IMU660RA_INIT_DATA, I2C_MEMADD_SIZE_8BIT,
                         imu660ra_config_file, IMU660RA_CONFIG_FILE_SIZE,
                         IMU660RA_I2C_TIMEOUT_MS);
  if (status != RP_OK) {
    return status;
  }

  /* 结束加载配置流。 */
  status = imu660ra_write_register(IMU660RA_INIT_CTRL, 0x01U);
  if (status != RP_OK) {
    return status;
  }
  system_delay_ms(20U);

  /* 检查配置是否加载完成。 */
  status = imu660ra_read_register(IMU660RA_INT_STA, &dat);
  if (status != RP_OK) {
    return status;
  }
  if (dat != 0x01U) {
    return RP_ERROR;
  }

  /* 开启性能模式，使能陀螺仪、加速度计、温度传感器。 */
  status = imu660ra_write_register(IMU660RA_PWR_CTRL, 0x0EU);
  if (status != RP_OK) {
    return status;
  }
  /* 加速度采集配置：性能模式、正常采集、50 Hz。 */
  status = imu660ra_write_register(IMU660RA_ACC_CONF, 0xA7U);
  if (status != RP_OK) {
    return status;
  }
  /* 陀螺仪采集配置：性能模式、正常采集、200 Hz。 */
  status = imu660ra_write_register(IMU660RA_GYR_CONF, 0xA9U);
  if (status != RP_OK) {
    return status;
  }

  /* 加速度计量程配置。 */
  switch (IMU660RA_ACC_SAMPLE_DEFAULT) {
    case IMU660RA_ACC_SAMPLE_SGN_2G:
      status = imu660ra_write_register(IMU660RA_ACC_RANGE, 0x00U);
      imu660ra_transition_factor[0] = 16384.0f;
      break;
    case IMU660RA_ACC_SAMPLE_SGN_4G:
      status = imu660ra_write_register(IMU660RA_ACC_RANGE, 0x01U);
      imu660ra_transition_factor[0] = 8192.0f;
      break;
    case IMU660RA_ACC_SAMPLE_SGN_8G:
      status = imu660ra_write_register(IMU660RA_ACC_RANGE, 0x02U);
      imu660ra_transition_factor[0] = 4096.0f;
      break;
    case IMU660RA_ACC_SAMPLE_SGN_16G:
      status = imu660ra_write_register(IMU660RA_ACC_RANGE, 0x03U);
      imu660ra_transition_factor[0] = 2048.0f;
      break;
    default:
      return RP_INVALID_PARAM;
  }
  if (status != RP_OK) {
    return status;
  }

  /* 陀螺仪量程配置。 */
  switch (IMU660RA_GYRO_SAMPLE_DEFAULT) {
    case IMU660RA_GYRO_SAMPLE_SGN_125DPS:
      status = imu660ra_write_register(IMU660RA_GYR_RANGE, 0x04U);
      imu660ra_transition_factor[1] = 262.4f;
      break;
    case IMU660RA_GYRO_SAMPLE_SGN_250DPS:
      status = imu660ra_write_register(IMU660RA_GYR_RANGE, 0x03U);
      imu660ra_transition_factor[1] = 131.2f;
      break;
    case IMU660RA_GYRO_SAMPLE_SGN_500DPS:
      status = imu660ra_write_register(IMU660RA_GYR_RANGE, 0x02U);
      imu660ra_transition_factor[1] = 65.6f;
      break;
    case IMU660RA_GYRO_SAMPLE_SGN_1000DPS:
      status = imu660ra_write_register(IMU660RA_GYR_RANGE, 0x01U);
      imu660ra_transition_factor[1] = 32.8f;
      break;
    case IMU660RA_GYRO_SAMPLE_SGN_2000DPS:
      status = imu660ra_write_register(IMU660RA_GYR_RANGE, 0x00U);
      imu660ra_transition_factor[1] = 16.4f;
      break;
    default:
      return RP_INVALID_PARAM;
  }
  if (status != RP_OK) {
    return status;
  }

  return RP_OK;
}

rp_status_t imu660ra_read_accel(int16_t accel[3])
{
  uint8_t dat[6];
  rp_status_t status;

  if (accel == NULL) {
    return RP_INVALID_PARAM;
  }
  status = imu660ra_read_registers(IMU660RA_ACC_ADDRESS, dat, 6U);
  if (status != RP_OK) {
    return status;
  }
  accel[0] = (int16_t)(((uint16_t)dat[1] << 8U) | dat[0]);
  accel[1] = (int16_t)(((uint16_t)dat[3] << 8U) | dat[2]);
  accel[2] = (int16_t)(((uint16_t)dat[5] << 8U) | dat[4]);
  return RP_OK;
}

